"""
Orchestrator (P1) — 编排器
按数据流串起 4 个 Agent：检索 → 画像 → 生成 → 审核，审核不通过时回炉重生成。

接口契约（来自 docs/接口约定.md）：
    run(岗位: str, 答题记录: list, question: str) -> dict

返回结构含画像、知识列表、培训内容、审核明细、评估结果、重试次数、协同日志。
"""

import time
from agents.retrieval import search_knowledge
from agents.profile import build_profile
from agents.generator import generate_content
from agents.reviewer import review_content
from agents.evaluator import evaluate

# 最大重试次数
MAX_RETRIES = 3


def run(岗位: str, 答题记录: list = None, question: str = "") -> dict:
    """
    主流程：把 4 个 Agent 按数据流串起来。
    审核不通过时带修改建议回炉重生成（最多 MAX_RETRIES 次）。

    参数:
        岗位:     如 "数控机床操作工"
        答题记录: 学员历史答题记录（可为空）
        question: 培训主题/问题（如 "数控机床安全操作"）

    返回:
        完整结果字典，供 app.py 展示全部中间过程
    """
    if 答题记录 is None:
        答题记录 = []
    if not question:
        question = f"{岗位}核心技能培训"

    协同日志 = []
    start_time = time.time()

    # ===== 步骤日志辅助函数 =====
    def log(msg: str):
        ts = f"[{time.time() - start_time:.2f}s]"
        协同日志.append(f"{ts} {msg}")

    # ================================================================
    # 步骤 1：知识检索（P2）
    # ================================================================
    log(f"🔍 开始知识检索: question='{question}'")
    知识列表 = search_knowledge(question)
    log(f"   检索完成: 返回 {len(知识列表)} 条知识")

    # ================================================================
    # 步骤 2：画像构建（P3）
    # ================================================================
    log(f"👤 开始画像构建: 岗位='{岗位}', 答题记录数={len(答题记录)}")
    画像 = build_profile(岗位, 答题记录)
    weak_skills = sorted(画像["技能掌握度"], key=画像["技能掌握度"].get)[:2]
    log(f"   画像完成: 弱项技能= {', '.join(weak_skills)}")

    # ================================================================
    # 步骤 3：内容生成（P3）
    # ================================================================
    log("📝 开始内容生成")
    培训内容 = generate_content(画像, 知识列表)
    log(f"   生成完成: 类型={培训内容['类型']}, 标题={培训内容['标题']}")

    # ================================================================
    # 步骤 4：三层审核（P4）+ 回炉闭环
    # ================================================================
    重试次数 = 0
    审核结果 = None

    while 重试次数 < MAX_RETRIES:
        log(f"🔎 开始审核 (第{重试次数+1}轮)")
        审核结果 = review_content(培训内容, 知识列表)
        log(f"   审核结果: 通过={审核结果['通过']}, 幻觉分数={审核结果['幻觉分数']}")

        if 审核结果["通过"]:
            log("✅ 审核通过，内容合格")
            break

        重试次数 += 1
        if 重试次数 < MAX_RETRIES:
            log(f"🔄 审核未通过，回炉重生成: {审核结果['修改建议']}")
            培训内容 = generate_content(画像, 知识列表, 修改建议=审核结果["修改建议"])
            log(f"   重生成完成: 标题={培训内容['标题']}")
        else:
            log(f"⚠️ 已达最大重试次数({MAX_RETRIES})，以当前内容通过")

    # ================================================================
    # 步骤 5：效果评估（P4）
    # ================================================================
    log("📊 开始效果评估")
    评估结果 = evaluate(培训内容, 知识列表, 画像)
    log(f"   评估完成: 综合分={评估结果['综合分']}")

    # ================================================================
    # 组装返回
    # ================================================================
    log(f"🏁 全流程完成，总耗时 {time.time() - start_time:.2f}s")

    return {
        "画像": 画像,
        "知识列表": 知识列表,
        "培训内容": 培训内容,
        "审核明细": 审核结果["审核明细"] if 审核结果 else {},
        "审核通过": 审核结果["通过"] if 审核结果 else False,
        "幻觉分数": 审核结果["幻觉分数"] if 审核结果 else 0.0,
        "评估结果": 评估结果,
        "重试次数": 重试次数,
        "协同日志": 协同日志,
    }


# ============================================================
# 独立运行示例
# ============================================================
if __name__ == "__main__":
    result = run(岗位="数控机床操作工", 答题记录=[
        {"技能": "M代码与编程", "正确": False},
        {"技能": "M代码与编程", "正确": False},
    ], question="数控机床M代码编程入门")

    print("=" * 60)
    print(f"画像: {result['画像']['岗位']}")
    print(f"技能掌握度: {result['画像']['技能掌握度']}")
    print(f"\n知识列表 ({len(result['知识列表'])} 条):")
    for k in result["知识列表"]:
        print(f"  - [{k['来源']}] {k['内容'][:50]}...")
    print(f"\n培训内容:")
    print(f"  类型: {result['培训内容']['类型']}")
    print(f"  标题: {result['培训内容']['标题']}")
    print(f"  引用: {result['培训内容']['引用来源']}")
    print(f"\n审核: {'✅ 通过' if result['审核通过'] else '❌ 未通过'}")
    print(f"  幻觉分数: {result['幻觉分数']}")
    print(f"  重试次数: {result['重试次数']}")
    print(f"\n评估:")
    for k, v in result["评估结果"].items():
        print(f"  {k}: {v}")
    print(f"\n协同日志:")
    for line in result["协同日志"]:
        print(f"  {line}")
