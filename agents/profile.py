"""
画像 Agent (P3)
根据岗位和答题记录，推算技能掌握度，构建学习者画像。

接口契约（来自 docs/接口约定.md）：
    输入: 岗位 (str), 答题记录 (list)
    输出: {"岗位": str, "技能掌握度": {技能名: 0~1}}

冷启动时（答题记录为空），用岗位→技能先验填初值。
"""

# ============================================================
# 岗位→技能先验表（stub 数据，模拟岗位能力模型）
# ============================================================
_POSITION_SKILL_PRIOR = {
    "数控机床操作工": {
        "安全操作规程": 0.65,
        "切削参数选择": 0.45,
        "M代码与编程": 0.30,
        "工件装夹与找正": 0.70,
        "量具使用与检测": 0.60,
        "设备维护保养": 0.55,
        "缺陷识别与排除": 0.25,
    },
    "CNC编程员": {
        "安全操作规程": 0.50,
        "切削参数选择": 0.75,
        "M代码与编程": 0.80,
        "工件装夹与找正": 0.40,
        "量具使用与检测": 0.55,
        "设备维护保养": 0.35,
        "缺陷识别与排除": 0.30,
    },
    "质检员": {
        "安全操作规程": 0.50,
        "切削参数选择": 0.30,
        "M代码与编程": 0.10,
        "工件装夹与找正": 0.20,
        "量具使用与检测": 0.85,
        "设备维护保养": 0.40,
        "缺陷识别与排除": 0.75,
    },
}


def build_profile(岗位: str, 答题记录: list = None) -> dict:
    """
    根据岗位和答题记录，推算技能掌握度。

    当前为 stub 版本：
    - 冷启动（无答题记录）：直接用岗位先验表
    - 有答题记录：在先验基础上做简单调整（每答对一题对应技能 +0.05，上限 1.0）

    后续替换为真正的 DKT / 知识追踪模型。

    参数:
        岗位: 如 "数控机床操作工"
        答题记录: 列表，每个元素形如 {"技能": "...", "正确": True/False}
                  为空或 None 时走冷启动逻辑

    返回:
        {"岗位": str, "技能掌握度": {str: float}}
    """
    if 答题记录 is None:
        答题记录 = []

    # 获取先验值（未知岗位给默认值）
    skills = _POSITION_SKILL_PRIOR.get(岗位, {
        "安全操作规程": 0.40,
        "切削参数选择": 0.40,
        "M代码与编程": 0.40,
        "工件装夹与找正": 0.40,
        "量具使用与检测": 0.40,
        "设备维护保养": 0.40,
        "缺陷识别与排除": 0.40,
    }).copy()

    # stub 调整：答题记录影响的技能更新
    for record in 答题记录:
        技能 = record.get("技能", "")
        正确 = record.get("正确", False)
        if 技能 in skills:
            if 正确:
                skills[技能] = min(1.0, skills[技能] + 0.05)
            else:
                skills[技能] = max(0.1, skills[技能] - 0.05)

    return {"岗位": 岗位, "技能掌握度": skills}


# ============================================================
# 独立运行示例
# ============================================================
if __name__ == "__main__":
    # 冷启动：无答题记录
    profile = build_profile("数控机床操作工")
    print("冷启动画像（数控机床操作工）:")
    for skill, level in profile["技能掌握度"].items():
        bar = "█" * int(level * 20) + "░" * (20 - int(level * 20))
        print(f"  {skill}: {bar} {level:.2f}")

    # 有答题记录
    记录 = [
        {"技能": "切削参数选择", "正确": True},
        {"技能": "切削参数选择", "正确": True},
        {"技能": "M代码与编程", "正确": False},
    ]
    profile2 = build_profile("数控机床操作工", 记录)
    print("\n学习后画像（做了 3 道题后）:")
    for skill, level in profile2["技能掌握度"].items():
        bar = "█" * int(level * 20) + "░" * (20 - int(level * 20))
        print(f"  {skill}: {bar} {level:.2f}")
