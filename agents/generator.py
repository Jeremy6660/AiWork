def generate_content(画像: dict, 知识列表: list, 修改建议: str = "") -> dict:
    """
    根据画像和知识生成个性化培训内容。

    当前为 stub 版本：
    - 根据岗位从假模板库中选内容
    - 内容类型根据弱项技能决定：得分低的给教程，中等的给实操指南
    - 「修改建议」非空时在正文开头追加修改说明（模拟回炉重生成）

    后续替换为 LLM 生成（基于画像 + 知识列表做 prompt engineering）。

    参数:
        画像: build_profile 的输出，含 {"岗位": str, "技能掌握度": {...}}
        知识列表: search_knowledge 的输出，[{"内容": str, "来源": str}, ...]
        修改建议: 非空时表示这是审核未通过的回炉重生成

    返回:
        {"类型": str, "标题": str, "正文": str, "引用来源": [str]}
    """
    岗位 = 画像.get("岗位", "数控机床操作工")
    skills = 画像.get("技能掌握度", {})

    # 找最弱技能
    if skills:
        weak_skill = min(skills, key=skills.get)
    else:
        weak_skill = "安全操作规程"

    # 选模板：弱项给教程，其他给实操指南
    模板集 = _MOCK_TRAININGS.get(岗位, _MOCK_TRAININGS["数控机床操作工"])

    # 根据弱项程度选内容类型
    weak_level = skills.get(weak_skill, 0.5)
    if weak_level < 0.4:
        类型 = "教程"
        内容 = 模板集.get("教程", 模板集["实操指南"])
    elif weak_level < 0.6:
        类型 = "实操指南"
        内容 = 模板集.get("实操指南", 模板集["教程"])
    else:
        类型 = "阶梯项目"
        内容 = 模板集.get("阶梯项目", 模板集["教程"])

    result = {
        "类型": 类型,
        "标题": 内容["标题"],
        "正文": 内容["正文"],
        "引用来源": 内容["引用来源"],
    }

    # 回炉重生成：在正文前注明修改迭代
    if 修改建议:
        result["标题"] = result["标题"] + "（修正版）"
        result["正文"] = (
            f"> 📝 **根据审核反馈已修正**：{修改建议}\n\n"
            + result["正文"]
        )

    return result


